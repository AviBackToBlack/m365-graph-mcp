/** A name that can never break out of a quoted header value, whatever its source. */
const SAFE_NAME_RE = /^[A-Za-z0-9][A-Za-z0-9 /_+().-]{0,63}$/;

let byLowerCase: ReadonlyMap<string, string> | undefined;

function table(): ReadonlyMap<string, string> {
  if (byLowerCase !== undefined) return byLowerCase;
  const map = new Map<string, string>();
  const add = (name: string): void => {
    // The charset check is a second line of defense on top of the fixed lists.
    if (SAFE_NAME_RE.test(name) && !map.has(name.toLowerCase())) map.set(name.toLowerCase(), name);
  };
  for (const name of WINDOWS_ZONES) add(name);
  for (const name of DOCUMENTED_IANA) add(name);
  byLowerCase = map;
  return map;
}

/** Canonical spelling of an allowlisted time-zone name, or undefined. */
export function canonicalTimeZone(name: string): string | undefined {
  return table().get(name.toLowerCase());
}
